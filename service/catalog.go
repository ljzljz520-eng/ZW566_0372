func SLARules() []SLARule { return append([]SLARule(nil), slaRules...) }
func RuleFor(code string) (SLARule, bool) {
	for _, r := range slaRules {
		if r.Code == code {
			return r, true
		}
	}
	return SLARule{}, false
}
func RulesForCategory(category string) []SLARule {
	out := []SLARule{}
	for _, r := range slaRules {
		if r.Category == category {
			out = append(out, r)
		}
	}
	return out
}
func EscalationFor(code string) int {
	if r, ok := RuleFor(code); ok {
		return r.Escalation
	}
	return -1
}
